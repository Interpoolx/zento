/**
 * Widget component for displaying social media profile links.
 * Shows platform icon with customizable colors and hover animations.
 * @param props - Component props
 * @param props.content - Social link configuration including platform, username, and label
 * @param props.style - Optional inline styles
 * @param props.isEditing - Whether the widget is in edit mode
 * @param props.onClick - Optional click handler for edit mode
 * @returns Social media link widget with platform-specific icon
 */
export function SocialWidget({ content, style, isEditing, onClick }: SocialWidgetProps) {
  const platformColor = socialColors[content.platform] || '#6366f1';
  const icon = socialIcons[content.platform] || socialIcons.website;
  const widgetBackgroundColor = style?.backgroundColor || '#ffffff';
  const textColor = style?.color || 'inherit';

  return (
    <div
      className={cn(
        'group flex flex-col items-center justify-center p-6 h-full transition-all duration-500 cursor-pointer',
        'hover:scale-[1.05] active:scale-95',
        isEditing && 'ring-2 ring-primary-500/20'
      )}
      style={{
        ...style,
        backgroundColor: widgetBackgroundColor,
        color: textColor,
      }}
      onClick={onClick}
    >
      <div
        className="w-12 h-12 rounded-2xl flex items-center justify-center mb-3 shadow-lg group-hover:rotate-12 transition-all duration-500"
        style={{ backgroundColor: platformColor, color: '#ffffff' }}
      >
        <div className="scale-125">{icon}</div>
      </div>
      <div className="text-center min-w-0">
        <p className="font-bold truncate text-sm tracking-tight">{content.label || content.username}</p>
        {content.label && (
          <p className="text-[10px] opacity-60 font-medium truncate uppercase tracking-widest mt-0.5">
            {content.platform}
          </p>
        )}
      </div>
    </div>
  );
}
